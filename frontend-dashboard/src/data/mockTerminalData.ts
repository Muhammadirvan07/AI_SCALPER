const timeframeMinutes = {
  M5: 5,
  M15: 15,
  M30: 30,
  H1: 60,
} as const

const candlePattern = [
  0.12, -0.08, 0.2, 0.06, -0.14, 0.18, -0.03, 0.09, -0.11, 0.15, 0.04, -0.07,
]

const buildCandles = (
  symbol: string,
  timeframe: keyof typeof timeframeMinutes,
  base: number,
  unit: number,
  precision: number,
): MarketCandle[] => {
  const interval = timeframeMinutes[timeframe]
  const start = new Date('2026-07-24T07:30:00+09:00').getTime()
  let previousClose = base

  return Array.from({ length: 38 }, (_, index) => {
    const pattern = candlePattern[index % candlePattern.length] ?? 0
    const drift = (index - 19) * unit * 0.025
    const open = previousClose
    const close = open + pattern * unit + drift * 0.08
    const wick = (0.22 + (index % 5) * 0.045) * unit
    const high = Math.max(open, close) + wick
    const low = Math.min(open, close) - wick * 0.82
    previousClose = close

    return {
      id: `${symbol}-${timeframe}-${index.toString()}`,
      timestamp: new Date(start + index * interval * 60_000).toISOString(),
      open: Number(open.toFixed(precision)),
      high: Number(high.toFixed(precision)),
      low: Number(low.toFixed(precision)),
      close: Number(close.toFixed(precision)),
      volume: 48 + ((index * 37) % 112),
    }
  })
}

const createInstrument = (
  symbol: string,
  quote: string,
  latestPrice: number,
  precision: number,
  unit: number,
  details: Omit<
    MarketInstrument,
    | 'symbol'
    | 'quote'
    | 'latestPrice'
    | 'precision'
    | 'selectedTimeframe'
    | 'candles'
  >,
): MarketInstrument => ({
  symbol,
  quote,
  latestPrice,
  precision,
  selectedTimeframe: 'M15',
  ...details,
  candles: {
    M5: buildCandles(symbol, 'M5', latestPrice - unit * 0.8, unit, precision),
    M15: buildCandles(symbol, 'M15', latestPrice - unit * 0.8, unit, precision),
    M30: buildCandles(symbol, 'M30', latestPrice - unit * 0.8, unit * 1.15, precision),
    H1: buildCandles(symbol, 'H1', latestPrice - unit * 0.8, unit * 1.35, precision),
  },
})

